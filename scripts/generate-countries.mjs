// Regenerates src/lib/countryData.ts: every region libphonenumber-js knows,
// with its English name and calling code. Run after upgrading libphonenumber-js:
//   node scripts/generate-countries.mjs
// The backend validates against the same library (functions/_lib/phone.js), so
// any country the form offers is one the server accepts.
import { writeFileSync } from "node:fs";
import { getCountries, getCountryCallingCode } from "libphonenumber-js/max";

const names = new Intl.DisplayNames(["en"], { type: "region", fallback: "none" });

const rows = getCountries()
  .map((code) => [code, names.of(code), `+${getCountryCallingCode(code)}`])
  .filter(([, name]) => Boolean(name))
  .sort((a, b) => a[1].localeCompare(b[1], "en"));

const body = rows
  .map(([code, name, dial]) => `  [${JSON.stringify(code)}, ${JSON.stringify(name)}, ${JSON.stringify(dial)}],`)
  .join("\n");

writeFileSync(
  new URL("../src/lib/countryData.ts", import.meta.url),
  `// Generated by scripts/generate-countries.mjs — do not edit by hand.
// [ISO 3166-1 alpha-2, English name, calling code]
export const COUNTRY_DATA: ReadonlyArray<readonly [string, string, string]> = [
${body}
];
`
);
console.log(`Wrote ${rows.length} countries`);
